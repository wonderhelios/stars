import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const s=fs.readFileSync(new URL('../static/app.js',import.meta.url),'utf8');
const el={innerHTML:''}; const today=20738;
const ctx=vm.createContext({$:()=>el,Date:class extends Date {static now(){return today*86400000+5000;}},fmt:(v,n)=>v.toFixed(n)});
vm.runInContext(s.slice(s.indexOf('function metric('),s.indexOf('// 轮询后台')),ctx);
vm.runInContext(s.slice(s.indexOf('let execDailyRange'),s.indexOf('function renderMonitor(')),ctx);
ctx.renderExecDaily({});assert.match(el.innerHTML,/尚未提供/);
ctx.renderExecDaily({exec_daily:[],equity:100});assert.match(el.innerHTML,/暂无执行记录/);
const data={equity:100,exec_daily:Array.from({length:35},(_,i)=>({day:today-i,orders:2,notional:100,turnover:1,avg_slip_pct:i===0?null:.1}))};
ctx.renderExecDaily(data);assert.match(el.innerHTML,/7 个有记录日/);assert.match(el.innerHTML,/\$700.00/);assert.match(el.innerHTML,/今日 · 未结束/);
el.onclick({target:{closest:selector=>selector==='[data-exec-range]'?{dataset:{execRange:'30'}}:null}});
assert.match(el.innerHTML,/30 个有记录日/);assert.match(el.innerHTML,/1 \/ 3 页/);
el.onclick({target:{closest:selector=>selector==='[data-exec-page]'?{dataset:{execPage:'next'}}:null}});
assert.match(el.innerHTML,/2 \/ 3 页/);
ctx.renderExecDaily({equity:0,exec_daily:[{day:today,orders:1,notional:100,turnover:0,avg_slip_pct:null}]});
assert.doesNotMatch(el.innerHTML,/0.000%|0.00×/);
assert.match(el.innerHTML,/当前净值/);assert.match(el.innerHTML,/包含失败/);
console.log('✓ Daily execution handles UTC windows, paging, missing API, unknown slippage and invalid equity without inventing zero values');

ctx.renderExecDaily(data);
assert.match(el.innerHTML,/class="daily-exec-bar-value"[^>]*>\$100\.00<\/span>/);
assert.equal((el.innerHTML.match(/class="daily-exec-bar-date"/g)||[]).length,30);
assert.match(el.innerHTML,/金额刻度 · USD/);
assert.match(el.innerHTML,/可横向滚动/);
assert.doesNotMatch(el.innerHTML,/<title>/,'amounts must be visible without hovering');
console.log('✓ Every bar has a visible precise amount and date, with scale and scroll access');
