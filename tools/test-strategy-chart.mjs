import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const s=readFileSync(new URL('../static/app.js',import.meta.url),'utf8');
const ctx=vm.createContext({});
vm.runInContext(s.slice(s.indexOf('function strategyHistory('),s.indexOf('function renderLiveChart(')),ctx);
const base={account:'A',capital_baseline:{account:'a',equity:500,ts:100},net_deposit:2400,capital_flows:[{ts:400,effective_ts:300,amount:2500},{ts:500,effective_ts:500,amount:-100}]};
const history=[{ts:100,equity:500},{ts:200,equity:510},{ts:300,equity:3010},{ts:400,equity:2990},{ts:500,equity:2890},{ts:600,equity:2920}];
const result=ctx.strategyHistory(history,base);
assert.deepEqual(Array.from(result.history,p=>p.equity),[0,10,10,-10,-10,20]);
assert.equal(result.estimated,false);
assert.equal(ctx.equityWindow(result.history,'all',600).raw.length,6,'negative PNL must not vanish');
const late=ctx.strategyHistory(history,{...base,capital_flows:base.capital_flows.map(({effective_ts,...f})=>f)});
assert.equal(late.estimated,true,'legacy registration times must be identified as estimates');
assert.ok(ctx.strategyHistory(history,{...base,net_deposit:2401}).error);
assert.ok(ctx.strategyHistory(history,{...base,account:'B'}).error);
assert.deepEqual(history.map(p=>p.equity),[500,510,3010,2990,2890,2920],'never mutate account history');
const hour=3600000;
const series=ctx.strategyHistory([{ts:100,equity:500},{ts:10*hour,equity:3000},{ts:100*hour,equity:3010},{ts:101*hour,equity:3020}],{...base,net_deposit:2500,capital_flows:[{ts:10*hour,effective_ts:10*hour,amount:2500}]});
assert.deepEqual(Array.from(ctx.equityWindow(series.history,'day',101*hour).raw,p=>p.equity),[10,20],'flows preceding selected window remain deducted');
console.log('✓ Strategy curve removes deposits and withdrawals, preserves losses, respects effective times and window boundaries, detects inconsistent ledgers');
